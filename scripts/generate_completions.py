#!/usr/bin/env python3
"""Write Bash and PowerShell tab completion for offroad-autonomy and every script.

The completions are read from the argparse parsers themselves, so they can
never offer an option that does not exist. tests/test_completions.py fails
when the committed files fall behind a parser; regenerate after changing any
option:

    python scripts/generate_completions.py
"""

from __future__ import annotations

import argparse
import importlib.util
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from offroad_autonomy.main import build_parser as build_main_parser

SCRIPTS_DIR = ROOT / "scripts"
OUT_DIR = ROOT / "completions"
BASH_PATH = OUT_DIR / "offroad-autonomy.bash"
POWERSHELL_PATH = OUT_DIR / "offroad-autonomy.ps1"

MAIN_COMMAND = "offroad-autonomy"
BASH_PYTHONS = ("python", "python3")
# Windows installs the console script as an .exe and adds the py launcher.
POWERSHELL_COMMANDS = (
    MAIN_COMMAND,
    f"{MAIN_COMMAND}.exe",
    "python",
    "python.exe",
    "python3",
    "py",
    "py.exe",
)

# Both shells receive these words unquoted inside generated code, and the
# completers use "=", "|" and spaces as separators, so anything else is refused
# rather than emitted as a script that breaks or completes the wrong thing.
_SAFE_WORD = re.compile(r"^[A-Za-z0-9_.:/+-]+$")


@dataclass
class CommandSpec:
    options: list[str] = field(default_factory=list)
    #: Option -> "file", "none" or "choice:a|b" for the value that follows it.
    values: dict[str, str] = field(default_factory=dict)
    subcommands: list[str] = field(default_factory=list)
    positional: bool = False


def build_parser() -> argparse.ArgumentParser:
    return argparse.ArgumentParser(description=__doc__)


def _safe(word: str) -> str:
    if not _SAFE_WORD.match(word):
        raise ValueError(f"{word!r} cannot be written into a completion script")
    return word


def value_kind(action: argparse.Action) -> str:
    if action.choices is not None:
        return "choice:" + "|".join(_safe(str(choice)) for choice in action.choices)
    if action.type in (int, float):
        # A number has no candidates, and offering file names would mislead.
        return "none"
    # Every other value is a path or a name typed fresh: file names are what
    # the paths need and are harmless for the rest.
    return "file"


def describe(parser: argparse.ArgumentParser, key: str, specs: dict[str, CommandSpec]) -> None:
    """Flatten ``parser`` and its subcommands into ``specs``, keyed
    ``command`` and ``command:subcommand``."""
    spec = CommandSpec()
    specs[key] = spec
    # argparse has no public way to list a parser's arguments; _actions has
    # held them unchanged since Python 3.2 and every completion library reads it.
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            for name, subparser in action.choices.items():
                spec.subcommands.append(_safe(name))
                describe(subparser, f"{key}:{name}", specs)
            continue
        if not action.option_strings:
            spec.positional = True
            continue
        spec.options.extend(_safe(option) for option in action.option_strings)
        if action.nargs == 0:
            continue
        for option in action.option_strings:
            spec.values[option] = value_kind(action)


def _load_script_parser(path: Path) -> argparse.ArgumentParser:
    module_spec = importlib.util.spec_from_file_location(f"_completion_{path.stem}", path)
    module = importlib.util.module_from_spec(module_spec)
    # Dataclasses look their module up here while the class is created.
    sys.modules[module_spec.name] = module
    module_spec.loader.exec_module(module)
    build = getattr(module, "build_parser", None)
    if build is None:
        raise SystemExit(f"{path.name} has no build_parser(), so its options cannot be completed")
    return build()


def collect() -> dict[str, CommandSpec]:
    specs: dict[str, CommandSpec] = {}
    describe(build_main_parser(), MAIN_COMMAND, specs)
    for path in sorted(SCRIPTS_DIR.glob("*.py")):
        describe(_load_script_parser(path), _safe(path.name), specs)
    return specs


def _scripts(specs: dict[str, CommandSpec]) -> list[str]:
    return [key for key in specs if key.endswith(".py")]


_BASH_HEADER = """\
# Tab completion for offroad-autonomy and the repository scripts, in Bash.
# Generated by scripts/generate_completions.py from the argparse parsers:
# regenerate it after changing an option instead of editing it.
#
#   source completions/offroad-autonomy.bash    # add to ~/.bashrc to keep it
#
# Scripts complete after `python` or `python3`. Any other python command line
# falls back to file names, which replaces bash-completion's own completion of
# the interpreter's flags in shells that source this file.

"""

_BASH_BODY = """\
_offroad_value_kind() {
    local pair
    _offroad_kind=""
    for pair in $_offroad_values; do
        if [[ "${pair%%=*}" == "$1" ]]; then
            _offroad_kind="${pair#*=}"
            return 0
        fi
    done
    return 1
}

_offroad_complete_value() {
    case "$1" in
        file)
            compopt -o filenames 2>/dev/null
            mapfile -t COMPREPLY < <(compgen -f -- "$2")
            ;;
        choice:*)
            local choices="${1#choice:}"
            mapfile -t COMPREPLY < <(compgen -W "${choices//|/ }" -- "$2")
            ;;
    esac
}

# $1 is the spec key, $2 the index of the first word after the command.
_offroad_complete_from() {
    local key="$1" i="$2" word cur="${COMP_WORDS[COMP_CWORD]}"
    _offroad_spec "$key"
    while (( i < COMP_CWORD )); do
        word="${COMP_WORDS[i]}"
        if _offroad_value_kind "$word"; then
            if (( i + 1 == COMP_CWORD )); then
                _offroad_complete_value "$_offroad_kind" "$cur"
                return
            fi
            # Skip the value too, so a value spelled like a subcommand is not
            # taken for one.
            i=$((i + 2))
            continue
        fi
        if [[ " $_offroad_subs " == *" $word "* ]]; then
            key="$key:$word"
            _offroad_spec "$key"
        fi
        i=$((i + 1))
    done
    if [[ "$cur" != -* && -n "$_offroad_subs" ]]; then
        mapfile -t COMPREPLY < <(compgen -W "$_offroad_subs" -- "$cur")
        return
    fi
    if [[ "$cur" != -* && -n "$_offroad_positional" ]]; then
        _offroad_complete_value file "$cur"
        return
    fi
    mapfile -t COMPREPLY < <(compgen -W "$_offroad_opts" -- "$cur")
}

_offroad_autonomy_complete() {
    COMPREPLY=()
    _offroad_complete_from offroad-autonomy 1
}

_offroad_python_complete() {
    COMPREPLY=()
    local script="${COMP_WORDS[1]##*/}"
    if (( COMP_CWORD >= 2 )) && [[ " $_offroad_scripts " == *" $script "* ]]; then
        _offroad_complete_from "$script" 2
        return
    fi
    compopt -o default 2>/dev/null
}

"""


def render_bash(specs: dict[str, CommandSpec]) -> str:
    lines = [_BASH_HEADER, f'_offroad_scripts="{" ".join(_scripts(specs))}"\n\n']
    lines.append("_offroad_spec() {\n")
    lines.append('    _offroad_opts=""\n')
    lines.append('    _offroad_values=""\n')
    lines.append('    _offroad_subs=""\n')
    lines.append('    _offroad_positional=""\n')
    lines.append('    case "$1" in\n')
    for key in sorted(specs):
        spec = specs[key]
        lines.append(f"        {key})\n")
        lines.append(f'            _offroad_opts="{" ".join(spec.options)}"\n')
        values = " ".join(f"{option}={kind}" for option, kind in spec.values.items())
        if values:
            lines.append(f'            _offroad_values="{values}"\n')
        if spec.subcommands:
            lines.append(f'            _offroad_subs="{" ".join(spec.subcommands)}"\n')
        if spec.positional:
            lines.append("            _offroad_positional=1\n")
        lines.append("            ;;\n")
    lines.append("    esac\n")
    lines.append("}\n\n")
    lines.append(_BASH_BODY)
    lines.append(f"complete -F _offroad_autonomy_complete {MAIN_COMMAND}\n")
    lines.append(f"complete -F _offroad_python_complete {' '.join(BASH_PYTHONS)}\n")
    return "".join(lines)


_POWERSHELL_HEADER = """\
# Tab completion for offroad-autonomy and the repository scripts, in PowerShell.
# Generated by scripts/generate_completions.py from the argparse parsers:
# regenerate it after changing an option instead of editing it.
#
#   . .\\completions\\offroad-autonomy.ps1    # add to $PROFILE to keep it
#
# Scripts complete after python, python3 or py. When nothing here applies the
# completer returns nothing, and PowerShell falls back to file names.

"""

_POWERSHELL_BODY = """\
    $words = @()
    foreach ($element in $commandAst.CommandElements) {
        # The word under the cursor ends at the cursor; only finished words count.
        if ($element.Extent.EndOffset -lt $cursorPosition) {
            $words += $element.Extent.Text.Trim('"', "'")
        }
    }
    if ($words.Count -eq 0) {
        return
    }
    $command = Split-Path -Leaf $words[0]
    $key = $null
    $start = 1
    if ($command -eq 'offroad-autonomy' -or $command -eq 'offroad-autonomy.exe') {
        $key = 'offroad-autonomy'
    }
    elseif ($words.Count -ge 2 -and $spec.ContainsKey((Split-Path -Leaf $words[1]))) {
        $key = Split-Path -Leaf $words[1]
        $start = 2
    }
    if ($null -eq $key) {
        return
    }

    $current = $spec[$key]
    $kind = $null
    $i = $start
    while ($i -lt $words.Count) {
        $word = $words[$i]
        if ($current.Values.ContainsKey($word)) {
            if ($i + 1 -eq $words.Count) {
                $kind = $current.Values[$word]
                break
            }
            # Skip the value too, so a value spelled like a subcommand is not
            # taken for one.
            $i += 2
            continue
        }
        if ($current.Subcommands -contains $word) {
            $key = "${key}:${word}"
            $current = $spec[$key]
        }
        $i += 1
    }

    $candidates = @()
    $resultType = 'ParameterName'
    if ($null -ne $kind) {
        if (-not $kind.StartsWith('choice:')) {
            # Files are PowerShell's own fallback, and a number has no candidates.
            return
        }
        $candidates = $kind.Substring(7).Split('|')
        $resultType = 'ParameterValue'
    }
    elseif (-not $wordToComplete.StartsWith('-') -and $current.Subcommands.Count -gt 0) {
        $candidates = $current.Subcommands
        $resultType = 'ParameterValue'
    }
    elseif (-not $wordToComplete.StartsWith('-') -and $current.Positional) {
        return
    }
    else {
        $candidates = $current.Options
    }
    foreach ($candidate in $candidates) {
        if ($candidate -like "$wordToComplete*") {
            [System.Management.Automation.CompletionResult]::new(
                $candidate, $candidate, $resultType, $candidate
            )
        }
    }
"""


def _powershell_list(words: list[str]) -> str:
    return "@(" + ", ".join(f"'{word}'" for word in words) + ")"


def render_powershell(specs: dict[str, CommandSpec]) -> str:
    lines = [_POWERSHELL_HEADER, "$offroadCompleter = {\n"]
    lines.append("    param($wordToComplete, $commandAst, $cursorPosition)\n\n")
    # Kept inside the script block so dot-sourcing it adds no variable a
    # profile could collide with.
    lines.append("    $spec = @{\n")
    for key in sorted(specs):
        spec = specs[key]
        values = "; ".join(f"'{option}' = '{kind}'" for option, kind in spec.values.items())
        positional = "$false"
        if spec.positional:
            positional = "$true"
        lines.append(f"        '{key}' = @{{\n")
        lines.append(f"            Options = {_powershell_list(spec.options)}\n")
        lines.append(f"            Values = @{{ {values} }}\n")
        lines.append(f"            Subcommands = {_powershell_list(spec.subcommands)}\n")
        lines.append(f"            Positional = {positional}\n")
        lines.append("        }\n")
    lines.append("    }\n\n")
    lines.append(_POWERSHELL_BODY)
    lines.append("}\n\n")
    lines.append(
        f"Register-ArgumentCompleter -Native -CommandName "
        f"{_powershell_list(list(POWERSHELL_COMMANDS))} -ScriptBlock $offroadCompleter\n"
    )
    lines.append("Remove-Variable offroadCompleter\n")
    return "".join(lines)


def main() -> None:
    build_parser().parse_args()
    specs = collect()
    OUT_DIR.mkdir(exist_ok=True)
    # Fixed newlines: a Windows checkout must not write files the drift test
    # then reports as changed.
    BASH_PATH.write_text(render_bash(specs), encoding="utf-8", newline="\n")
    POWERSHELL_PATH.write_text(render_powershell(specs), encoding="utf-8", newline="\n")
    print(f"Wrote {BASH_PATH.relative_to(ROOT)} and {POWERSHELL_PATH.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
